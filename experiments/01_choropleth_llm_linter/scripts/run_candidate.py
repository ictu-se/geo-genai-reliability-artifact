#!/usr/bin/env python3
"""Run one candidate mapping script and capture logs for comparison."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
DATA_DIR = ROOT / "data/repos/Materials-for-Creating-maps-by-Artificial-Intelligence/data_choropleth"
RUNS_DIR = ROOT / "experiments/01_choropleth_llm_linter/outputs/candidate_runs"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("candidate", type=Path, help="Python file generated by a model or written as a baseline.")
    parser.add_argument("--prompt-id", default="manual", help="Prompt id from inputs/prompts_v0.json.")
    parser.add_argument("--timeout", type=int, default=120)
    args = parser.parse_args()

    candidate = args.candidate.resolve()
    if not candidate.exists():
        raise SystemExit(f"Candidate file not found: {candidate}")

    run_id = f"{args.prompt_id}_{candidate.stem}_{time.strftime('%Y%m%d_%H%M%S')}"
    run_dir = RUNS_DIR / run_id
    run_dir.mkdir(parents=True, exist_ok=True)

    env = os.environ.copy()
    env["CHOROPLETH_DATA_DIR"] = str(DATA_DIR)
    env["CHOROPLETH_OUTPUT_DIR"] = str(run_dir)

    started = time.time()
    try:
        proc = subprocess.run(
            [sys.executable, str(candidate)],
            cwd=ROOT,
            env=env,
            text=True,
            capture_output=True,
            timeout=args.timeout,
        )
        timed_out = False
    except subprocess.TimeoutExpired as exc:
        proc = exc
        timed_out = True

    elapsed = time.time() - started
    stdout = proc.stdout or ""
    stderr = proc.stderr or ""
    returncode = None if timed_out else proc.returncode

    (run_dir / "stdout.txt").write_text(stdout, encoding="utf-8")
    (run_dir / "stderr.txt").write_text(stderr, encoding="utf-8")
    metadata = {
        "candidate": str(candidate.relative_to(ROOT) if candidate.is_relative_to(ROOT) else candidate),
        "prompt_id": args.prompt_id,
        "run_dir": str(run_dir.relative_to(ROOT)),
        "returncode": returncode,
        "timed_out": timed_out,
        "elapsed_seconds": round(elapsed, 3),
        "data_dir_env": "CHOROPLETH_DATA_DIR",
        "output_dir_env": "CHOROPLETH_OUTPUT_DIR",
        "created_files": sorted(str(p.relative_to(run_dir)) for p in run_dir.rglob("*") if p.is_file()),
    }
    (run_dir / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(json.dumps(metadata, indent=2))

    if timed_out:
        raise SystemExit(124)
    raise SystemExit(returncode)


if __name__ == "__main__":
    main()

